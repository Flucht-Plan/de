let currentLang = 'de';

function applyLang(lang){
  currentLang = lang;
  document.documentElement.lang = lang;
  const dict = i18n[lang];
  document.querySelectorAll('[data-i18n]').forEach(el=>{
    const key = el.getAttribute('data-i18n');
    if(dict[key] !== undefined){ el.innerHTML = dict[key]; }
  });
  document.getElementById('pageTitle').textContent = dict['meta.title'];
  document.getElementById('metaDesc').setAttribute('content', dict['meta.desc']);
  document.querySelectorAll('.lang-switch button').forEach(b=>{
    b.classList.toggle('active', b.getAttribute('data-lang') === lang);
  });
  document.getElementById('hamburgerBtn').setAttribute('aria-label', lang==='de' ? 'Menü öffnen' : 'Open menu');
}

document.querySelectorAll('.lang-switch button').forEach(btn=>{
  btn.addEventListener('click', ()=> applyLang(btn.getAttribute('data-lang')));
});

/* ============ Header scroll shadow ============ */
const header = document.getElementById('siteHeader');
window.addEventListener('scroll', ()=>{
  header.classList.toggle('scrolled', window.scrollY > 12);
  document.getElementById('toTop').classList.toggle('show', window.scrollY > 500);
}, {passive:true});

/* ============ Mobile nav ============ */
const hamburgerBtn = document.getElementById('hamburgerBtn');
const mainNav = document.getElementById('mainNav');
hamburgerBtn.addEventListener('click', ()=>{
  const open = mainNav.classList.toggle('open');
  hamburgerBtn.setAttribute('aria-expanded', open);
});
mainNav.querySelectorAll('a').forEach(a=>a.addEventListener('click', ()=>{
  mainNav.classList.remove('open');
  hamburgerBtn.setAttribute('aria-expanded', 'false');
}));

/* ============ Back to top ============ */
document.getElementById('toTop').addEventListener('click', ()=>{
  window.scrollTo({top:0, behavior:'smooth'});
});

/* ============ Scroll reveal ============ */
const observer = new IntersectionObserver((entries)=>{
  entries.forEach(entry=>{
    if(entry.isIntersecting){ entry.target.classList.add('in'); observer.unobserve(entry.target); }
  });
}, {threshold:0.12});
document.querySelectorAll('.reveal').forEach(el=>observer.observe(el));

/* ============ Contact form validation ============ */
const form = document.getElementById('contactForm');
const successBox = document.getElementById('formSuccess');
form.addEventListener('submit', function(e){
  e.preventDefault();
  let valid = true;
  const nameField = document.getElementById('fname').closest('.field');
  const emailField = document.getElementById('femail').closest('.field');
  const msgField = document.getElementById('fmessage').closest('.field');
  const emailVal = document.getElementById('femail').value.trim();
  const emailOk = /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(emailVal);

  [nameField, emailField, msgField].forEach(f=>f.classList.remove('invalid'));

  if(document.getElementById('fname').value.trim() === ''){ nameField.classList.add('invalid'); valid = false; }
  if(!emailOk){ emailField.classList.add('invalid'); valid = false; }
  if(document.getElementById('fmessage').value.trim() === ''){ msgField.classList.add('invalid'); valid = false; }

  if(valid){
    const name = document.getElementById('fname').value.trim();
    const company = document.getElementById('fcompany').value.trim();
    const email = document.getElementById('femail').value.trim();
    const phone = document.getElementById('fphone').value.trim();
    const message = document.getElementById('fmessage').value.trim();

    const subjectText = (currentLang === 'de' ? 'Neue Anfrage von ' : 'New request from ') + name + ' \u2013 FluchtPlanPro';
    const bodyLines = currentLang === 'de' ? [
      'Name: ' + name,
      'Firma: ' + (company || '-'),
      'E-Mail: ' + email,
      'Telefon: ' + (phone || '-'),
      '',
      'Nachricht:',
      message
    ] : [
      'Name: ' + name,
      'Company: ' + (company || '-'),
      'Email: ' + email,
      'Phone: ' + (phone || '-'),
      '',
      'Message:',
      message
    ];

    const mailtoLink = 'mailto:fireevacs@gmail.com'
      + '?subject=' + encodeURIComponent(subjectText)
      + '&body=' + encodeURIComponent(bodyLines.join('\n'));

    window.location.href = mailtoLink;

    successBox.classList.add('show');
    form.reset();
    setTimeout(()=> successBox.classList.remove('show'), 9000);
  }
});

